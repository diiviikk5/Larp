import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import { Coordinator } from '../server/coordinator.mjs';
import { Host } from '../server/host.mjs';
import { AppRecords } from '../server/app-records.mjs';

process.env.LARP_CLOUD = 'off';
const root = await fs.mkdtemp(path.join(os.tmpdir(), 'larp-workspace-'));
const skillDir = path.join(root, 'skills');
await fs.mkdir(path.join(skillDir, 'shared-review'), { recursive: true });
await fs.writeFile(path.join(skillDir, 'shared-review', 'SKILL.md'), '# Shared review\nCheck the evidence. SHARED_SKILL_MARKER');
await fs.writeFile(path.join(skillDir, 'shared-review', 'larp-install.json'), JSON.stringify({ slug: 'shared-review', title: 'Shared review', revision: '1234567890', source: 'test fixture' }));
const prompts = [];
let appMode = false;
const mock = http.createServer(async (req, res) => {
  let raw = ''; for await (const chunk of req) raw += chunk;
  const body = JSON.parse(raw); const prompt = body.messages[1].content; prompts.push(prompt);
  const call = (name, args) => ({ role: 'assistant', content: null, tool_calls: [{ id: 'tool1', type: 'function', function: { name, arguments: JSON.stringify(args) } }] });
  let message;
  if (appMode) message = prompt.includes('Your app request succeeded') ? { role: 'assistant', content: 'The app record was created.' } : call('app_request', { id: 'studio', method: 'POST', path: 'records', body: { collection: 'projects', record: { name: 'Agent project' } } });
  else if (prompt.includes('Task: Lead asks:')) message = { role: 'assistant', content: 'Tester checked the evidence using Shared review. Looks good.' };
  else if (prompt.includes('Tester replied:')) message = { role: 'assistant', content: 'Lead and Tester both loaded Shared review and completed the review.' };
  else if (prompt.includes('Created agent Tester')) message = call('ask_agent', { name: 'Tester', request: 'Check the evidence with your assigned skill.' });
  else message = call('spawn_agent', { name: 'Tester', skills: ['shared-review'] });
  res.writeHead(200, { 'Content-Type': 'application/json' }); res.end(JSON.stringify({ choices: [{ message }], usage: { prompt_tokens: 100, completion_tokens: 20, total_tokens: 120 } }));
});
await new Promise((r) => mock.listen(0, '127.0.0.1', r));
const c = new Coordinator({ dataDir: path.join(root, 'coordinator'), meko: null }); await c.init(); await c.listen({ port: 0, host: '127.0.0.1' });
const url = `http://127.0.0.1:${c.server.address().port}`;
const owner = c.createSpaceWithOwner({ spaceName: 'Local team', kind: 'build', ownerName: 'Owner' });
const registration = c.registerHost(owner.person.id, { name: 'One laptop' });
const apps = new AppRecords(path.join(root, 'apps')); await apps.sync('studio', { projects: [] }, 0);
const host = new Host({ url, token: registration.token, dataDir: path.join(root, 'host'), skillsDir: skillDir, appCall: (args) => apps.call(args), appContext: async () => [{ name: 'studio', kind: 'creative', text: JSON.stringify(await apps.read('studio')) }] });
await host.start();
const until = async (fn) => { for (let i = 0; i < 200; i++) { if (fn()) return; await new Promise((r) => setTimeout(r, 80)); } throw new Error('Timed out'); };
try {
  const lead = await host.addAgent({ ownerToken: owner.token, name: 'Lead', runtime: 'openai', model: 'test', spaceIds: [owner.space.id], baseUrl: `http://127.0.0.1:${mock.address().port}`, skills: ['shared-review'], useApps: true });
  const task = c.createTask(owner.person.id, { spaceId: owner.space.id, agentId: lead.id, title: 'Team review', instructions: 'Create a tester and review together.', kind: 'general' });
  await until(() => ['needs_review', 'failed'].includes(task.status));
  assert.equal(task.status, 'needs_review', task.result?.error);
  assert.equal(Object.keys(c.s.agents).length, 2); assert.equal(task.asks.length, 1);
  const child = c.s.tasks[task.asks[0].childId]; assert.equal(child.ownerId, lead.ownerId); assert.equal(child.status, 'accepted');
  assert.ok(task.log.some((l) => l.kind === 'skill')); assert.ok(child.log.some((l) => l.kind === 'skill'));
  assert.ok(prompts.every((p) => p.includes('SHARED_SKILL_MARKER')));
  assert.equal((await fs.readFile(path.join(skillDir, 'shared-review', 'SKILL.md'), 'utf8')).includes('MARKER'), true);
  console.log('PASS: one host spawns specialist, shares pinned skill, delegates and receives answer');
  c.messageTask(owner.person.id, task.id, { text: 'Add a concise final explanation.' });
  await until(() => task.status === 'needs_review'); assert.ok(prompts.at(-1).includes('Add a concise final explanation.'));
  console.log('PASS: follow-up resumes same task with feedback');
  appMode = true;
  const appTask = c.createTask(owner.person.id, { spaceId: owner.space.id, agentId: lead.id, title: 'App write', instructions: 'Create a studio project.', kind: 'general' });
  await until(() => Object.values(c.s.approvals).some((a) => a.taskId === appTask.id && a.status === 'pending'));
  assert.equal((await apps.read('studio')).data.projects.length, 0);
  const approval = Object.values(c.s.approvals).find((a) => a.taskId === appTask.id && a.status === 'pending');
  c.resolveApproval(owner.person.id, approval.id, { decision: 'approve' });
  await until(() => ['needs_review', 'failed'].includes(appTask.status)); assert.equal(appTask.status, 'needs_review', appTask.result?.error);
  assert.equal((await apps.read('studio')).data.projects.length, 1); assert.ok(appTask.log.some((l) => l.kind === 'app'));
  console.log('PASS: app write cannot execute before approval; receipt and continuation recorded');
  await assert.rejects(() => apps.sync('studio', { projects: [] }, 0), /changed/);
  await apps.sync('citylines', { trips: [{ id: 'demo' }] }, 0, 'demo');
  await apps.sync('citylines', { trips: [] }, 0, 'personal');
  assert.equal((await apps.read('citylines', 'personal')).data.trips.length, 0);
  assert.equal((await apps.read('citylines', 'demo')).data.trips.length, 1);
  assert.throws(() => c.messageTask('intruder', task.id, { text: 'stop' }));
  const messages = []; c.telegram.send = async (chatId, text) => { messages.push(text); return { message_id: 444 }; };
  c.telegram.config.links[owner.person.id] = { chatId: 99 };
  await c.telegram.handle({ message: { chat: { id: 99, type: 'private' }, text: `/trace ${task.id}` } });
  assert.ok(messages.at(-1).includes(task.id));
  await c.telegram.handle({ message: { chat: { id: 99, type: 'private' }, text: `/chat ${task.id} Continue from Telegram` } });
  assert.ok(task.feedback.some((f) => f.text === 'Continue from Telegram'));
  console.log('PASS: Telegram trace and chat target the same desktop task; access checks and stale-write conflict checks pass');
} finally { await host.stop(); await c.close(); await new Promise((r) => mock.close(r)); }
